/**
 * Generates src/sicons/: Sakani's own icon set (Sicons), one module per icon.
 *
 *   node scripts/sicons/generate.mjs
 *
 * Same 1,626 icons as the Figma "Icons" component set, built from Lucide's
 * shapes with the Sakani treatment: softened corners (round.mjs), the same
 * rule the Figma set uses. Each module carries the icon's rounded paths.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadIcon, decompose, lucideVersion } from '../glass-icons/decompose.mjs';
import { roundIcon } from './round.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.join(root, 'src/sicons');
const iconsDir = path.join(outDir, 'icons');
const { names } = JSON.parse(fs.readFileSync(path.join(root, 'scripts/glass-icons/figma-icons.json'), 'utf8'));
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

fs.rmSync(iconsDir, { recursive: true, force: true });
fs.mkdirSync(iconsDir, { recursive: true });
const header = (source) => `// Generated by scripts/sicons/generate.mjs -- do not edit by hand.\n// Shape data: ${source}\n`;

const exports = [];
const stats = { lucide: 0, figma: 0, tight: 0, missing: [] };
for (const name of names) {
  const icon = await loadIcon(name);
  if (!icon) { stats.missing.push(name); continue; }
  if (icon.figma) stats.figma++; else stats.lucide++;
  const { all } = decompose(icon.node);
  const { paths, radius } = roundIcon(all);
  if (radius < 4) stats.tight++;
  const comp = `Sicon${pascal(name)}`;
  fs.writeFileSync(
    path.join(iconsDir, `${name}.ts`),
    `${header(icon.source)}import { createSicon } from '../createSicon';\n\n` +
      `export const ${comp} = /*#__PURE__*/ createSicon(${JSON.stringify(name)}, ${JSON.stringify(paths)});\n` +
      `export default ${comp};\n`,
  );
  exports.push({ name, comp });
}

fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  `${header(`${stats.lucide} icons from lucide-react ${lucideVersion}, ${stats.figma} from the Sakani Figma icon set`)}` +
    `export { Sicon, createSicon } from './createSicon';\n` +
    `export type { SiconProps, SiconData, SiconFC } from './createSicon';\n` +
    `export { siconNames } from './names';\n` +
    `export type { SiconName } from './names';\n\n` +
    exports.map(({ name, comp }) => `export { ${comp} } from './icons/${name}';`).join('\n') + '\n',
);
fs.writeFileSync(
  path.join(outDir, 'names.ts'),
  `${header('Figma "Icons" component set')}export const siconNames = ${JSON.stringify(exports.map((e) => e.name))} as const;\n\nexport type SiconName = (typeof siconNames)[number];\n`,
);
console.log(`sicons: ${exports.length} generated (${stats.lucide} lucide, ${stats.figma} figma); ${stats.tight} use the 1px radius`);
if (stats.missing.length) { console.error('MISSING:', stats.missing.join(', ')); process.exit(1); }
