/**
 * Generates src/icons/: the Sakani icon set, built from Tabler Icons
 * (tabler.io/icons, MIT) -- the same icons as the Figma "↳ Icons (Tabler)"
 * page, one module per icon.
 *
 *   node scripts/icons/generate.mjs
 *
 * Outline icons become `Icon<Name>` (IconHome), filled ones
 * `Icon<Name>Filled` (IconHomeFilled), matching Tabler's own naming so its
 * search (tabler.io/icons) works for finding a name. Re-run after upgrading
 * @tabler/icons.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const pkg = path.join(root, 'node_modules/@tabler/icons');
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const outline = JSON.parse(fs.readFileSync(path.join(pkg, 'tabler-nodes-outline.json'), 'utf8'));
const filled = JSON.parse(fs.readFileSync(path.join(pkg, 'tabler-nodes-filled.json'), 'utf8'));

const outDir = path.join(root, 'src/icons');
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const header = `// Generated by scripts/icons/generate.mjs -- do not edit by hand.\n// Shape data: @tabler/icons ${version} (MIT).\n`;

const exports = [];
const seen = new Set();
for (const [style, data] of [['outline', outline], ['filled', filled]]) {
  const dir = path.join(outDir, style);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  for (const name of Object.keys(data).sort()) {
    const comp = 'Icon' + pascal(name) + (style === 'filled' ? 'Filled' : '');
    if (seen.has(comp)) throw new Error('duplicate component name ' + comp);
    seen.add(comp);
    const paths = data[name].filter(([tag]) => tag === 'path').map(([, a]) => a.d);
    fs.writeFileSync(
      path.join(dir, `${name}.ts`),
      `${header}import { createIcon } from '../createIcon';\n\n` +
        `export const ${comp} = /*#__PURE__*/ createIcon(${JSON.stringify(name)}, ${JSON.stringify(paths)}${style === 'filled' ? ', true' : ''});\n` +
        `export default ${comp};\n`,
    );
    exports.push({ comp, file: `./${style}/${name}`, name, style });
  }
}

fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  header +
    `export { createIcon } from './createIcon';\n` +
    `export type { IconProps, SakaniIcon } from './createIcon';\n` +
    `export type { IconComponent } from './types';\n` +
    `export { iconNames, filledIconNames } from './names';\n\n` +
    exports.map((e) => `export { ${e.comp} } from '${e.file}';`).join('\n') + '\n',
);
fs.writeFileSync(
  path.join(outDir, 'names.ts'),
  header +
    `export const iconNames = ${JSON.stringify(exports.filter((e) => e.style === 'outline').map((e) => e.name))} as const;\n\n` +
    `export const filledIconNames = ${JSON.stringify(exports.filter((e) => e.style === 'filled').map((e) => e.name))} as const;\n`,
);
console.log(`icons: ${exports.filter((e) => e.style === 'outline').length} outline, ${exports.filter((e) => e.style === 'filled').length} filled (@tabler/icons ${version})`);
