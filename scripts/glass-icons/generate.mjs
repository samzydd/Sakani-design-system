/**
 * Generates src/glass-icons/: one module per Tabler outline icon (5,184), the
 * same set and names as `@sakaniui/react/icons` and the Figma "Glass Icons /
 * <Category>" component sets.
 *
 *   node scripts/glass-icons/generate.mjs
 *
 * Shapes come from @tabler/icons (tabler-nodes-outline.json, MIT). Each icon's
 * glass is its exact silhouette (silhouette.mjs): the source strokes plus every
 * area they enclose, with the inner lines drawn white on the glass at render
 * time. Re-run after upgrading @tabler/icons.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { silhouette } from './silhouette.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.join(root, 'src/glass-icons');
const iconsDir = path.join(outDir, 'icons');
const tablerDir = path.join(root, 'node_modules/@tabler/icons');
const tablerVersion = JSON.parse(fs.readFileSync(path.join(tablerDir, 'package.json'), 'utf8')).version;
const nodes = JSON.parse(fs.readFileSync(path.join(tablerDir, 'tabler-nodes-outline.json'), 'utf8'));
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

fs.rmSync(iconsDir, { recursive: true, force: true });
fs.mkdirSync(iconsDir, { recursive: true });

const header = (source) => `// Generated by scripts/glass-icons/generate.mjs -- do not edit by hand.\n// Shape data: ${source}\n`;

const names = Object.keys(nodes).sort();
let withAccent = 0;
for (const name of names) {
  const { strokes, fills, accent } = silhouette(nodes[name]);
  if (accent) withAccent++;
  const comp = `Glass${pascal(name)}`;
  fs.writeFileSync(
    path.join(iconsDir, `${name}.ts`),
    `${header(`Tabler Icons ${tablerVersion} (MIT), icon "${name}"`)}import { createGlassIcon } from '../createGlassIcon';\n\n` +
      `export const ${comp} = /*#__PURE__*/ createGlassIcon(${JSON.stringify(name)}, ${JSON.stringify([strokes, fills, accent ?? 0])});\n` +
      `export default ${comp};\n`,
  );
}

fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  `${header(`${names.length} icons from Tabler Icons ${tablerVersion} (MIT)`)}` +
    `export { GlassIcon, GlassIconSvg, createGlassIcon } from './createGlassIcon';\n` +
    `export type { GlassIconProps, GlassIconData, GlassIconComponent } from './createGlassIcon';\n` +
    `export { glassIconNames } from './names';\n` +
    `export type { GlassIconName } from './names';\n\n` +
    names.map((n) => `export { Glass${pascal(n)} } from './icons/${n}';`).join('\n') + '\n',
);
fs.writeFileSync(
  path.join(outDir, 'names.ts'),
  `${header(`Tabler Icons ${tablerVersion}`)}export const glassIconNames = ${JSON.stringify(names)} as const;\n\nexport type GlassIconName = (typeof glassIconNames)[number];\n`,
);

console.log(`glass icons: ${names.length} generated from Tabler ${tablerVersion}; accent disc on ${withAccent}`);
