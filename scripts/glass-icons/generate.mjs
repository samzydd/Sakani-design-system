/**
 * Generates src/glass-icons/: one module per icon in the Sakani icon set.
 *
 *   node scripts/glass-icons/generate.mjs
 *
 * The set is the Figma "Icons" component set (figma-icons.json, 1,626 names).
 * Each name is taken from lucide-react's own shape data (__iconNode); the few
 * Lucide no longer ships (brand logos) come from figma-extra.json.
 *
 * Each icon is split into glass body, lines and accent disc by decompose.mjs,
 * the same rules the Figma "Glass Icons" build applies to the Icons set.
 * Re-run after upgrading lucide-react or changing the Figma set.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadIcon, decompose, lucideVersion } from './decompose.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.join(root, 'src/glass-icons');
const iconsDir = path.join(outDir, 'icons');

const { names } = JSON.parse(fs.readFileSync(path.join(here, 'figma-icons.json'), 'utf8'));
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

fs.rmSync(iconsDir, { recursive: true, force: true });
fs.mkdirSync(iconsDir, { recursive: true });

const header = (source) =>
  `// Generated by scripts/glass-icons/generate.mjs -- do not edit by hand.\n// Shape data: ${source}\n`;

const exports = [];
const stats = { lucide: 0, figma: 0, missing: [], aliases: [], pure: 0 };

for (const name of names) {
  const icon = await loadIcon(name);
  if (!icon) { stats.missing.push(name); continue; }
  if (icon.figma) stats.figma++; else stats.lucide++;
  if (icon.via) stats.aliases.push(`${name}->${icon.via}`);
  const { body, detail, accent, pure } = decompose(icon.node);
  if (pure) stats.pure++;
  const comp = `Glass${pascal(name)}`;
  fs.writeFileSync(
    path.join(iconsDir, `${name}.ts`),
    `${header(icon.source)}import { createGlassIcon } from '../createGlassIcon';\n\n` +
      `export const ${comp} = /*#__PURE__*/ createGlassIcon(${JSON.stringify(name)}, ${JSON.stringify([body, detail, accent, pure ? 1 : 0])});\n` +
      `export default ${comp};\n`,
  );
  exports.push({ name, comp });
}

const index =
  `${header(`${stats.lucide} icons from lucide-react ${lucideVersion}, ${stats.figma} from the Sakani Figma icon set`)}` +
  `export { GlassIcon, GlassIconSvg, createGlassIcon } from './createGlassIcon';\n` +
  `export type { GlassIconProps, GlassIconData, GlassIconComponent } from './createGlassIcon';\n` +
  `export { glassIconNames } from './names';\n` +
  `export type { GlassIconName } from './names';\n\n` +
  exports.map(({ name, comp }) => `export { ${comp} } from './icons/${name}';`).join('\n') + '\n';
fs.writeFileSync(path.join(outDir, 'index.ts'), index);

fs.writeFileSync(
  path.join(outDir, 'names.ts'),
  `${header('Figma "Icons" component set')}export const glassIconNames = ${JSON.stringify(exports.map((e) => e.name))} as const;\n\nexport type GlassIconName = (typeof glassIconNames)[number];\n`,
);

console.log(`glass icons: ${exports.length} generated (${stats.lucide} lucide, ${stats.figma} figma)`);
console.log(`line-only (drawn as a glass stroke): ${stats.pure}`);
console.log(`aliases followed: ${stats.aliases.length}`);
const dupes = stats.aliases.filter((a) => names.includes(a.split('->')[1]));
if (dupes.length) console.log(`aliases that now draw the same shape as another icon in the set (${dupes.length}): ${dupes.join(', ')}`);
if (stats.missing.length) { console.error('MISSING:', stats.missing.join(', ')); process.exit(1); }
